#!/usr/bin/env python3
"""Emit the order-gate scene for the client's player id.

The scene copies the proven client-gate deck (docs/evidence/client-gate-2026-11-15/commands/gate-scene.cmd):
a 3x3 wood deck 2 m above the fixture ground at (-30.17, 36.46, 0.03), a bowl whose creator is the
joining player (so that client owns the claim and may toggle feeding / issue orders), chest A with
coal for the Tidy, and chest B as the routing target.

    python3 make-scene.py <playerId> > commands/gate-orders-scene.cmd
"""
import sys

player = int(sys.argv[1])
g = 38.46   # deck level; ground under it is 36.46 in the fixture world
p = 38.56   # pieces sit 0.10 above the deck, as in the gate scene

lines = [
    "# Order-gate scene — deck, bowl owned by the joining player, chest A with coal, chest B empty.",
    "# Generated by make-scene.py for player %d. Mirrors the client-gate scene." % player,
    "cleanup",
    "hold on",
]
for x in (-32.17, -30.17, -28.17):
    for z in (-1.97, -0.05, 2.03):
        lines.append("spawn wood_floor %.2f %.2f %.2f" % (x, g, z))
lines += [
    "spawn piece_groundtorch_green -31.4 %.2f 1.7" % (g + 0.10),
    "spawn piece_groundtorch_green -28.8 %.2f 1.7" % (g + 0.10),
    "spawn husnisse_bowl -32.17 %.2f -0.97 %d" % (p, player),
    "spawn piece_chest_wood -28.17 %.2f -0.97" % p,
    "spawn piece_chest_wood -28.17 %.2f 2.03" % p,
    "wait 3",
    "husnisse claims",
    "fill husnisse_bowl CookedMeat 3",
    "fill piece_chest_wood Coal 6 0",
    # 0.3b: a chest only receives from the nisse when it is on the storage network; chest A is the
    # Tidy source and chest B the destination, so both carry the flag.
    "zdoset piece_chest_wood husnisse_net bool true 0",
    "zdoset piece_chest_wood husnisse_net bool true 1",
    "zdo husnisse_bowl husnisse_bowl_init",
    "zdo husnisse_bowl husnisse_bowl_satiety",
    "zdo piece_chest_wood items 0",
    "zdo piece_chest_wood items 1",
    "husnisse status",
]
print("\n".join(lines))
