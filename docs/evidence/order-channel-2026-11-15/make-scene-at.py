#!/usr/bin/env python3
"""Emit the order-gate scene for the client's settled position and player id.

Geometry is chosen from the rig findings in RESULT.md ("Rig findings that blocked the
remaining two checks"), not from taste:

  * the player is NOT moved (a transform set fights the server's copy of the position and
    snaps back mid-order), so the scene is built around the position the client reports;
  * the bowl sits ~4.6 m from the player: the Empty Pockets handover drops the stacks at the
    nisse's own feet (bowl + 1.5 m), so anything under 3 m lets the player auto-pick its own
    handover back up and the trip lands `moved=0` (proven on 2026-11-15);
  * every piece stands on a ground-level wood_floor grid at the player's own y: a dedicated
    server has no terrain colliders, so a character with nothing under it falls through the
    world (nisse seen at y=-4496) and a floating deck decays;
  * chest B (the destination) is at the SMALLER x of the two chests, because both
    `console husnisse_rule net piece_chest_wood on <i>` and the harness `fill`/`container`
    indices address containers sorted by x then z. Chest B is therefore index 0 (the one put
    on the storage network) and chest A, holding the coal, is index 1;
  * chest A is the nearest container to the player, because the client probe's `alt <prefab>`
    resolves the nearest one - that is what a player's Alt-click does too.

    python3 make-scene-at.py <px> <py> <pz> <playerId> > client/gate-orders-tidy.cmd
"""
import sys

px, py, pz, player = float(sys.argv[1]), float(sys.argv[2]), float(sys.argv[3]), int(sys.argv[4])

FLOOR = round(py, 2)          # deck at the player's feet: above the terrain, never buried
PIECE = round(py + 0.10, 2)   # pieces sit 0.10 above the deck, as in the proven scenes

# Plan view, relative to the player.
BOWL = (-4.60, -0.40)         # 4.6 m away: the handover drop zone stays out of pickup range
CHEST_A = (1.50, 1.70)        # 2.3 m away and the nearest container: the Tidy source (index 1)
CHEST_B = (-0.90, 3.20)       # smaller x than chest A, so index 0: the destination, on the network

TILES_X = (-4, -2, 0, 2)
TILES_Z = (0, 2, 4)

lines = [
    "# Order-gate scene for the client's settled position (%.2f, %.2f, %.2f), player %d."
    % (px, py, pz, player),
    "# Generated by make-scene-at.py. Do not move the player: build the scene around it.",
    "# bowl at %.2f,%.2f (%.1f m from the player) | chest A (coal, nearest, index 1) at %.2f,%.2f"
    % (px + BOWL[0], pz + BOWL[1], (BOWL[0] ** 2 + BOWL[1] ** 2) ** 0.5,
       px + CHEST_A[0], pz + CHEST_A[1]),
    "# chest B (destination, index 0, on the network) at %.2f,%.2f" % (px + CHEST_B[0], pz + CHEST_B[1]),
    "cleanup",
    "hold on",
]
for dx in TILES_X:
    for dz in TILES_Z:
        lines.append("spawn wood_floor %.2f %.2f %.2f" % (px + dx, FLOOR, pz + dz))
lines += [
    "spawn husnisse_bowl %.2f %.2f %.2f %d" % (px + BOWL[0], PIECE, pz + BOWL[1], player),
    "spawn piece_chest_wood %.2f %.2f %.2f" % (px + CHEST_A[0], PIECE, pz + CHEST_A[1]),
    "spawn piece_chest_wood %.2f %.2f %.2f" % (px + CHEST_B[0], PIECE, pz + CHEST_B[1]),
    "wait 3",
    "husnisse claims",
    "fill husnisse_bowl CookedMeat 3",
    # 0.3b: a chest only receives from the nisse when it is on the storage network.
    "console husnisse_rule net piece_chest_wood on 0",
    "console husnisse_rule list",
    "fill piece_chest_wood Coal 6 1",
    "zdo husnisse_bowl husnisse_bowl_init",
    "zdo husnisse_bowl husnisse_bowl_satiety",
    "zdo piece_chest_wood husnisse_net 0",
    "zdo piece_chest_wood husnisse_net 1",
    "container piece_chest_wood 0",
    "container piece_chest_wood 1",
    "husnisse claims",
    "husnisse status",
    # Hold the scene while the client works: the harness destroys its spawns at scenario end.
    # The dump after the first hold is the server-side answer to "did the destination chest gain
    # the coal and did the source empty" - a client-spawned copy of a server-spawned chest reads
    # its contents stale, so the client's own `containers` line is not that evidence.
    "wait 120",
    "container piece_chest_wood 0",
    "container piece_chest_wood 1",
    "husnisse queue",
    "husnisse status",
    "wait 120",
]
print("\n".join(lines))
